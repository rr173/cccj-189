"""The committed capture-v2 hand sample, asserted exactly.

``demo/capture/evolving-sample`` is generated by
``demo/capture/gen_evolving.py --flavor hand``:

* version 1: ``gross`` (field ``f-amount``) is an ``int``;
* version 2 (effective at commit_seq 2): the same field is renamed to
  ``amount`` and widened to ``float``; ``currency`` is added with backfill
  ``"USD"``;
* commit 1 (version 1) updates a row before the switch; commit 2 (version 2)
  updates it after.

Both events must be written to target column ``amount``, both images must
carry ``currency="USD"``, and the numeric values must be unchanged.
"""

from __future__ import annotations

import json
import subprocess
import sys
import unittest
from pathlib import Path

from ddreduce.capture.importer import run_import
from ddreduce.capture.verifier import VERDICT_MATCH, run_verify
from ddreduce.logmodel import load_changelog
from ddreduce.model import Database
from ddreduce.replay import validate_log_inputs
from ddreduce.schema import load_schema

from .helpers import ROOT, TempDir

SAMPLE = ROOT / "demo" / "capture" / "evolving-sample"


class EvolvingSampleTest(unittest.TestCase):
    def setUp(self):
        self.tmp = TempDir()

    def tearDown(self):
        self.tmp.cleanup()

    def _import(self, out: Path | None = None, through: int = 2):
        out = out or self.tmp.path / "package"
        result = run_import(
            SAMPLE / "archive", SAMPLE / "snapshot", SAMPLE / "schema.json",
            out, through,
            history_path=SAMPLE / "archive" / "schema-history.json",
        )
        return result, out

    def test_hand_computed_conversion(self):
        result, out = self._import()
        lines = [json.loads(line) for line in
                 (out / "changes.jsonl").read_text("utf-8").splitlines()]
        self.assertEqual([tx["tx_id"] for tx in lines], ["A", "B"])

        ev_a = lines[0]["events"][0]
        self.assertEqual(ev_a["key"], {"key": "k"})
        self.assertEqual(ev_a["before"],
                         {"key": "k", "amount": 10.0, "currency": "USD"})
        self.assertEqual(ev_a["after"],
                         {"key": "k", "amount": 20.0, "currency": "USD"})
        ev_b = lines[1]["events"][0]
        self.assertEqual(ev_b["before"],
                         {"key": "k", "amount": 20.0, "currency": "USD"})
        self.assertEqual(ev_b["after"],
                         {"key": "k", "amount": 30.0, "currency": "USD"})
        # The old name never leaks and the values did not change.
        raw = (out / "changes.jsonl").read_text("utf-8")
        self.assertNotIn("gross", raw)

        # Old row and updated row both keep the backfill; the snapshot is
        # converted too, not copied.
        snapshot_row = json.loads(
            (out / "snapshot" / "accounts.jsonl").read_text("utf-8")
        )
        self.assertEqual(snapshot_row,
                         {"key": "k", "amount": 10.0, "currency": "USD"})

        counts = result.report["counts"]
        self.assertEqual(counts["exported_transactions"], 2)
        self.assertEqual(counts["commits_version_checked"], 2)
        self.assertEqual(result.report["schema_history"]["switch_points"],
                         [{"version": 2, "effective_commit_seq": 2}])
        # Every output event names the version it was written with.
        map_rows = [json.loads(line) for line in
                    (out / "capture-map.jsonl").read_text("utf-8").splitlines()]
        self.assertEqual([r["source"]["schema_version"] for r in map_rows],
                         [1, 2])

    def test_independent_verification_matches(self):
        _result, out = self._import()
        verify = run_verify(
            SAMPLE / "archive", SAMPLE / "snapshot", SAMPLE / "schema.json",
            2, out, history_path=SAMPLE / "archive" / "schema-history.json",
        )
        self.assertEqual(verify.verdict, VERDICT_MATCH, verify.failures)
        self.assertEqual(verify.failures, [])

    def test_package_is_consumable_by_existing_log_tools(self):
        _result, out = self._import()
        schema = load_schema(out / "schema.json")
        db = Database.load(schema, out / "snapshot")
        log = load_changelog(out / "changes.jsonl", schema)
        validated = validate_log_inputs(
            schema, (out / "schema.json").read_text("utf-8"), db, log
        )
        final = validated.normalize({0, 1}).final_database()
        self.assertEqual(final.rows['accounts/str:"k"'].data,
                         {"key": "k", "amount": 30.0, "currency": "USD"})

    def test_deterministic_regeneration(self):
        regen = self.tmp.path / "regen"
        proc = subprocess.run(
            [sys.executable, "-I",
             str(ROOT / "demo" / "capture" / "gen_evolving.py"),
             "--out", str(regen), "--flavor", "hand",
             "--seed", "7", "--shards", "2"],
            capture_output=True, text=True,
        )
        self.assertEqual(proc.returncode, 0, proc.stderr)

        def tree(root: Path):
            return {p.relative_to(root).as_posix(): p.read_bytes()
                    for p in sorted(root.rglob("*")) if p.is_file()}

        self.assertEqual(tree(regen / "archive"), tree(SAMPLE / "archive"))
        self.assertEqual(tree(regen / "snapshot"), tree(SAMPLE / "snapshot"))
        self.assertEqual((regen / "schema.json").read_bytes(),
                         (SAMPLE / "schema.json").read_bytes())


class NameClashSampleTest(unittest.TestCase):
    """A same-named column with a different field ID is never merged."""

    def setUp(self):
        self.tmp = TempDir()
        proc = subprocess.run(
            [sys.executable, "-I",
             str(ROOT / "demo" / "capture" / "gen_evolving.py"),
             "--out", str(self.tmp.path / "clash"), "--flavor", "nameclash",
             "--seed", "3", "--shards", "1"],
            capture_output=True, text=True,
        )
        assert proc.returncode == 0, proc.stderr
        self.base = self.tmp.path / "clash"

    def tearDown(self):
        self.tmp.cleanup()

    def test_old_field_goes_to_its_own_target_column(self):
        out = self.base / "pkg"
        run_import(
            self.base / "archive", self.base / "snapshot",
            self.base / "schema.json", out, 2,
            history_path=self.base / "archive" / "schema-history.json",
        )
        snapshot_row = json.loads(
            (out / "snapshot" / "accounts.jsonl").read_text("utf-8")
        )
        # f-legacy keeps its values; the *new* field reusing the name "amount"
        # is backfilled and never receives the legacy value.
        self.assertEqual(snapshot_row,
                         {"key": "k", "amount_legacy": 7, "amount": 0.0})
        ev = json.loads(
            (out / "changes.jsonl").read_text("utf-8").splitlines()[0]
        )["events"][0]
        self.assertEqual(ev["after"]["amount_legacy"], 9)
        self.assertEqual(ev["after"]["amount"], 0.0)
        verify = run_verify(
            self.base / "archive", self.base / "snapshot",
            self.base / "schema.json", 2, out,
            history_path=self.base / "archive" / "schema-history.json",
        )
        self.assertEqual(verify.verdict, VERDICT_MATCH, verify.failures)


if __name__ == "__main__":
    unittest.main()
